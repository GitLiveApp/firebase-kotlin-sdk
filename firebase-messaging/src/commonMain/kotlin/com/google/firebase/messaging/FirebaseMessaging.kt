package com.google.firebase.messaging

import dev.gitlive.firebase.messaging.UPSTREAM_SEND_DECOMMISSIONED
import com.google.android.gms.tasks.Task
import dev.gitlive.firebase.messaging.DELIVERY_METRICS_ANDROID_ONLY
import dev.gitlive.firebase.messaging.NOTIFICATION_DELEGATION_ANDROID_ONLY
import dev.gitlive.firebase.messaging.REGISTER_NOT_AVAILABLE

/**
 * Firebase Cloud Messaging, as the Android SDK's `com.google.firebase.messaging.FirebaseMessaging`. Receiving messages
 * is platform code on every platform (`FirebaseMessagingService` on Android).
 *
 * The JS SDK has no topic subscription (a web client's token is subscribed from a server with the Admin SDK) and no
 * auto-init (a token is only ever generated by [getToken]): those members do nothing on JS and carry
 * `@UnsupportedOnJs`, so code compiled for JS gets a warning until it opts in.
 */
public expect class FirebaseMessaging {
    /** Deletes the registration token of this app instance, so it stops receiving messages. */
    public fun deleteToken(): Task<Nothing?>

    /** The registration token of this app instance, requested from the backend if needed. */
    public fun getToken(): Task<String>

    /** Deprecated in the SDK and Android-only: sends an upstream message, a feature FCM decommissioned. */
    @Deprecated(UPSTREAM_SEND_DECOMMISSIONED, level = DeprecationLevel.ERROR)
    public fun send(message: RemoteMessage)

    /** Subscribes this app instance to [topic]. A no-op on JS, whose SDK has no client-side topic subscription. */
    public fun subscribeToTopic(topic: String): Task<Nothing?>

    /** Unsubscribes this app instance from [topic]. A no-op on JS, whose SDK has no client-side topic subscription. */
    public fun unsubscribeFromTopic(topic: String): Task<Nothing?>

    /**
     * Whether the registration token is generated automatically at startup, which apps turn off until the user has
     * consented. Always false on JS, where a token is only generated by [getToken]; setting it does nothing there.
     */
    public var isAutoInitEnabled: Boolean

    /*
     * The Android-only members below are declared so that common code calling them fails with a message saying so, rather
     * than with an unresolved reference; Android code in androidMain calls the real members (see api/android-sdk/exclusions.txt).
     */

    /** Android only: whether message delivery metrics are exported to BigQuery. */
    @Deprecated(DELIVERY_METRICS_ANDROID_ONLY, level = DeprecationLevel.ERROR)
    public fun deliveryMetricsExportToBigQueryEnabled(): Boolean

    /** Android only: exports message delivery metrics to BigQuery. */
    @Deprecated(DELIVERY_METRICS_ANDROID_ONLY, level = DeprecationLevel.ERROR)
    public fun setDeliveryMetricsExportToBigQuery(enable: Boolean)

    /** Android only: whether notifications are delegated to the device's proxy. */
    @Deprecated(NOTIFICATION_DELEGATION_ANDROID_ONLY, level = DeprecationLevel.ERROR)
    public fun isNotificationDelegationEnabled(): Boolean

    /** Android only: delegates notifications to the device's proxy. */
    @Deprecated(NOTIFICATION_DELEGATION_ANDROID_ONLY, level = DeprecationLevel.ERROR)
    public fun setNotificationDelegationEnabled(enable: Boolean): Task<Nothing?>

    /** Not available yet: added to the Android SDK after the version this SDK depends on. */
    @Deprecated(REGISTER_NOT_AVAILABLE, level = DeprecationLevel.ERROR)
    public fun register(): Task<Nothing?>

    /** Not available yet: added to the Android SDK after the version this SDK depends on. */
    @Deprecated(REGISTER_NOT_AVAILABLE, level = DeprecationLevel.ERROR)
    public fun unregister(): Task<Nothing?>

    public companion object {
        /** The scope of the registration token, `FCM`; a remnant of the Instance ID API. */
        @Deprecated("The registration token has no scope any more; getToken() returns the FCM token")
        public val INSTANCE_ID_SCOPE: String

        /** The [FirebaseMessaging] singleton. */
        public fun getInstance(): FirebaseMessaging
    }
}
